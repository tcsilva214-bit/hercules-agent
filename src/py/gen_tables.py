"""Generate Python-compatible character tables for HERCULES Build 3's checker (src/pychar.rs).
Run with the hub's Python version (3.14). Output is deterministic."""
import re, sys, unicodedata

def ranges(pred):
    out, start = [], None
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            ok = False
        else:
            ok = pred(chr(cp))
        if ok and start is None:
            start = cp
        elif not ok and start is not None:
            out.append((start, cp - 1)); start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out

W = re.compile(r"\w"); D = re.compile(r"\d"); S = re.compile(r"\s")
tables = {
    "WORD": ranges(lambda c: bool(W.fullmatch(c))),
    "DIGIT": ranges(lambda c: bool(D.fullmatch(c))),
    "STRSPACE": ranges(lambda c: c.isspace()),
    "PRINTABLE": ranges(lambda c: c.isprintable()),
}
# re's \s must equal str.isspace (py/mod.rs uses one table for both)
assert all(bool(S.fullmatch(chr(c))) == chr(c).isspace() for c in range(0x110000) if not 0xD800 <= c <= 0xDFFF)
# int() of a \d character must be its offset in its run of ten (py/mod.rs digit_value)
for a, b in tables["DIGIT"]:
    assert all(unicodedata.decimal(chr(c)) == (c - a) % 10 for c in range(a, b + 1))
# re.IGNORECASE equivalents of each ASCII letter (Unicode mode)
fold = {}
for L in "abcdefghijklmnopqrstuvwxyz":
    pat = re.compile(re.escape(L), re.I)
    fold[L] = [cp for cp in range(0x110000) if not 0xD800 <= cp <= 0xDFFF and pat.fullmatch(chr(cp))]
# str.lower() where it is not one char, or where it differs from a simple per-char mapping
lower = {}
for cp in range(0x110000):
    if 0xD800 <= cp <= 0xDFFF:
        continue
    c = chr(cp); l = c.lower()
    if l != c:
        lower[cp] = l
w = sys.stdout.write
w(f"//! Generated by gen_tables.py with Python {sys.version.split()[0]} (Unicode {unicodedata.unidata_version}). Do not edit.\n")
w("//! Character classes exactly as the bridge's Python sees them: re's \\w, \\d, \\s, str.isspace, str.isprintable,\n")
w("//! the re.IGNORECASE equivalents of ASCII letters, and str.lower().\n\n")
for name, rs in tables.items():
    w(f"pub static {name}: [(u32, u32); {len(rs)}] = [\n")
    for a, b in rs:
        w(f"    (0x{a:X}, 0x{b:X}),\n")
    w("];\n\n")
w(f"pub static FOLD: [(char, &[char]); 26] = [\n")
for L, cps in fold.items():
    w(f"    ('{L}', &[" + ", ".join(f"'\\u{{{cp:X}}}'" for cp in cps) + "]),\n")
w("];\n\n")
items = sorted(lower.items())
w(f"pub static LOWER: [(u32, &str); {len(items)}] = [\n")
for cp, l in items:
    w(f"    (0x{cp:X}, \"" + "".join(f"\\u{{{ord(x):X}}}" for x in l) + "\"),\n")
w("];\n")
